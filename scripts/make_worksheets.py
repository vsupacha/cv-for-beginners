"""Generate the answer-sheet sources worksheets/0N_sheet.qmd.

Students open the PDF on a tablet, write in the tables and boxes, and hand it in.
Tables are raw LaTeX with fixed column widths and tall rows for handwriting.

    python scripts/make_worksheets.py
    cd worksheets && quarto render        # needs xelatex (TinyTeX) and the Angsana New font
"""

from pathlib import Path

TEXT_MM = 166            # A4 width minus margins
COL_PAD_MM = 4.3         # tabcolsep on both sides of a column


def table(headers, rows, widths, row_mm=9):
    """headers: list of str, rows: list of lists, widths: relative column widths."""
    total = sum(widths)
    usable = TEXT_MM - COL_PAD_MM * len(widths)
    cols = "|".join(f"W{{{usable * w / total:.1f}mm}}" for w in widths)
    lines = [r"\begin{center}", rf"\begin{{tabular}}{{|{cols}|}}\hline",
             " & ".join(rf"\textbf{{{h}}}" for h in headers) + r" \\\hline"]
    for row in rows:
        row = list(row) + [""] * (len(headers) - len(row))
        row[0] = rf"\rule{{0pt}}{{{row_mm}mm}}" + row[0]
        lines.append(" & ".join(row) + r" \\\hline")
    lines += [r"\end{tabular}", r"\end{center}"]
    return "\n```{=latex}\n" + "\n".join(lines) + "\n```\n\n"


def box(question, mm=30):
    return f"\n{question}\n\n\\answerbox[{mm}mm]\n\n"


def name_block():
    return table(["ชื่อ-นามสกุล", "รหัสนักศึกษา", "หน้าที่ในส่วนที่ 1 / 2 / 3"],
                 [[""], [""], [""]], [5, 3, 4], row_mm=8) + \
        table(["กลุ่ม", "วันที่", "แหล่งภาพที่ใช้ (SOURCE)"], [[""]], [2, 3, 7], row_mm=8)


def start_block(n, check):
    return (f"## เริ่มต้น: โค้ดตั้งต้น\n\n"
            f"$\\square$ รัน `code/{n}_start.py` แล้ว{check}\n\n")


def page(n, title, subtitle, body):
    head = (f"---\ntitle: \"ใบบันทึกผล ใบงาน {int(n)}: {title}\"\n"
            f"subtitle: \"{subtitle}\"\n---\n\n")
    note = ("เขียนผลลงในตารางและกรอบคำตอบ แล้วส่งไฟล์ PDF เมื่อจบคาบ "
            f"ขั้นตอนและโค้ดของแต่ละข้ออยู่ในหน้าเว็บใบงาน {int(n)}\n\n")
    return head + note + name_block() + "\n" + start_block(n, CHECK[n]) + body


